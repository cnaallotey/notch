import AppKit

struct ClipboardItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let date: Date
}

/// Recent text copied to the clipboard. Kept in memory only, and anything a password
/// manager marks as concealed or transient is never recorded.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipboardItem] = []

    private let pasteboard = NSPasteboard.general
    private var changeCount: Int
    private var timer: Timer?
    private let limit = 20

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        changeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    deinit { timer?.invalidate() }

    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        changeCount = pasteboard.changeCount
        insert(item.text)
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
    }

    func clear() {
        items.removeAll()
    }

    private func poll() {
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        let types = pasteboard.types ?? []
        guard !types.contains(where: { Self.ignoredTypes.contains($0.rawValue) }),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        insert(text)
    }

    private func insert(_ text: String) {
        items.removeAll { $0.text == text }
        items.insert(ClipboardItem(text: text, date: Date()), at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
    }

    #if DEBUG
    func loadPreviewItems() {
        let now = Date()
        items = [
            ClipboardItem(text: "https://github.com/cnaallotey/notch", date: now.addingTimeInterval(-40)),
            ClipboardItem(text: "Let's move the design review to Thursday at 3pm.", date: now.addingTimeInterval(-600)),
            ClipboardItem(text: "scripts/build.sh --run", date: now.addingTimeInterval(-3600)),
            ClipboardItem(text: "func remaining(at date: Date) -> TimeInterval", date: now.addingTimeInterval(-7200)),
        ]
    }
    #endif
}
